#!/usr/bin/env python3
"""
energy_log.py - log Apple Silicon power while a workload runs.

Two independent sources are logged in parallel:
  1. powermetrics -> CPU / GPU / ANE package power (needs sudo)
  2. macmon       -> CPU+GPU+ANE power, DRAM power (ram_power) and
                     whole-system power (sys_power, SMC), plus RAM/swap usage.
                     Install once with: brew install macmon

Energy is computed only over the "active" window (GPU busy), so model-load time is
excluded, and the idle baseline (measured before the run) is subtracted.

Usage:
  sudo python3 energy_log.py --name q4_np1 --tokens 128 -- <workload command ...>

Example:
  sudo python3 energy_log.py --name 3b_q4_np2 --tokens 1024 -- \
      llama-batched-bench -m 3b-q4.gguf -c 4096 -ngl 99 -npp 128 -ntg 512 -npl 2

Outputs (current folder):
  <name>_raw.csv   per-second samples
  results.csv      one summary row per run (appended)
"""
import argparse
import csv
import json
import os
import re
import shutil
import statistics
import subprocess
import sys
import threading
import time

NAN = float("nan")
PM_CMD = ["powermetrics", "-i", "1000", "--samplers", "cpu_power,gpu_power,ane_power"]
MM_CMD = ["macmon", "pipe"]
RE_PART = re.compile(r"^(CPU|GPU|ANE) Power:\s+([\d.]+)\s*mW")
RE_COMB = re.compile(r"^Combined Power.*:\s+([\d.]+)\s*mW")

pm_samples = []  # (t, cpu_w, gpu_w, ane_w, combined_w)
mm_samples = []  # (t, sys_w, pkg_w, ram_w, ram_used_gb, swap_mb)


def pm_reader(proc):
    cur = {}
    for line in proc.stdout:
        line = line.strip()
        m = RE_PART.match(line)
        if m:
            cur[m.group(1)] = float(m.group(2)) / 1000.0
            continue
        m = RE_COMB.match(line)
        if m:
            pm_samples.append((time.time(), cur.get("CPU", 0.0), cur.get("GPU", 0.0),
                               cur.get("ANE", 0.0), float(m.group(1)) / 1000.0))
            cur = {}


def mm_reader(proc):
    for line in proc.stdout:
        line = line.strip()
        if not line.startswith("{"):
            continue
        try:
            d = json.loads(line)
        except ValueError:
            continue
        mem = d.get("memory", {})
        mm_samples.append((time.time(),
                           float(d.get("sys_power", NAN)),
                           float(d.get("all_power", NAN)),
                           float(d.get("ram_power", NAN)),
                           mem.get("ram_usage", 0) / 1e9,
                           mem.get("swap_usage", 0) / 1e6))


def window(samples, a, b, idx):
    return [s[idx] for s in samples if a <= s[0] <= b and s[idx] == s[idx]]


def mean_sd(samples, a, b, idx):
    vals = window(samples, a, b, idx)
    if not vals:
        return NAN, 0.0, 0
    return statistics.mean(vals), (statistics.pstdev(vals) if len(vals) > 1 else 0.0), len(vals)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True)
    ap.add_argument("--tokens", type=int, default=0,
                    help="total tokens GENERATED by the workload (for J/token)")
    ap.add_argument("--idle", type=int, default=30, help="idle baseline seconds")
    ap.add_argument("cmd", nargs=argparse.REMAINDER)
    args = ap.parse_args()
    cmd = args.cmd[1:] if args.cmd and args.cmd[0] == "--" else args.cmd
    if not cmd:
        sys.exit("Give the workload command after --")
    if os.geteuid() != 0:
        sys.exit("Run with sudo (powermetrics needs root)")
    if shutil.which("macmon") is None:
        sys.exit("macmon not found. Install it with: brew install macmon")

    pm = subprocess.Popen(PM_CMD, stdout=subprocess.PIPE, text=True, bufsize=1)
    mm = subprocess.Popen(MM_CMD, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
                          text=True, bufsize=1)
    threading.Thread(target=pm_reader, args=(pm,), daemon=True).start()
    threading.Thread(target=mm_reader, args=(mm,), daemon=True).start()

    print(f"[1/3] idle baseline for {args.idle}s - don't touch the Mac...")
    ti0 = time.time()
    time.sleep(args.idle)
    ti1 = time.time()

    print("[2/3] running workload...")
    t0 = time.time()
    subprocess.run(cmd)
    t1 = time.time()
    time.sleep(2)

    pm.terminate()
    mm.terminate()
    wall = t1 - t0

    # raw dump
    with open(f"{args.name}_raw.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["t_unix", "source", "cpu_w", "gpu_w", "ane_w", "pkg_w", "sys_w",
                    "ram_w", "ram_used_gb", "swap_mb"])
        for s in pm_samples:
            w.writerow([f"{s[0]:.2f}", "powermetrics", s[1], s[2], s[3], s[4], "", "", "", ""])
        for s in mm_samples:
            w.writerow([f"{s[0]:.2f}", "macmon", "", "", "", s[2], s[1], s[3], s[4], s[5]])

    # Active window = seconds where the GPU is busy (excludes model load).
    act = [s[0] for s in pm_samples if t0 <= s[0] <= t1 + 2 and s[2] > 0.5]
    if act:
        a0, a1 = min(act) - 1.0, max(act)
        dur = a1 - a0
    else:
        a0, a1, dur = t0, t1, wall
        print("  WARNING: no GPU-active samples found, using whole run window")

    idle_pkg, _, _ = mean_sd(pm_samples, ti0, ti1, 4)
    run_pkg, run_pkg_sd, n_pm = mean_sd(pm_samples, a0, a1, 4)
    idle_mm_pkg, _, _ = mean_sd(mm_samples, ti0, ti1, 2)
    run_mm_pkg, _, _ = mean_sd(mm_samples, a0, a1, 2)
    idle_sys, _, _ = mean_sd(mm_samples, ti0, ti1, 1)
    run_sys, run_sys_sd, n_mm = mean_sd(mm_samples, a0, a1, 1)
    idle_ram, _, _ = mean_sd(mm_samples, ti0, ti1, 3)
    run_ram, _, _ = mean_sd(mm_samples, a0, a1, 3)
    ram_used = max(window(mm_samples, t0, t1 + 2, 4) or [NAN])
    swap_max = max(window(mm_samples, t0, t1 + 2, 5) or [NAN])

    e_pkg = (run_pkg - idle_pkg) * dur
    e_ram = (run_ram - idle_ram) * dur
    e_sys = (run_sys - idle_sys) * dur
    tok = args.tokens
    jpt = lambda e: e / tok if tok else NAN
    tps = tok / dur if tok else NAN

    print("\n[3/3] summary")
    print(f"  wall / active time    : {wall:.1f} s / {dur:.1f} s  ({n_pm} powermetrics / {n_mm} macmon samples)")
    print(f"  package power (pm)    : {run_pkg:.2f} +- {run_pkg_sd:.2f} W  (idle {idle_pkg:.2f} W)")
    print(f"  package power (macmon): {run_mm_pkg:.2f} W  (idle {idle_mm_pkg:.2f} W)")
    print(f"  DRAM power (macmon)   : {run_ram:.3f} W  (idle {idle_ram:.3f} W)")
    print(f"  system power (macmon) : {run_sys:.2f} +- {run_sys_sd:.2f} W  (idle {idle_sys:.2f} W)")
    print(f"  net energy  pkg / DRAM / system : {e_pkg:.1f} J / {e_ram:.2f} J / {e_sys:.1f} J")
    if tok:
        print(f"  J/token     pkg / DRAM / system : {jpt(e_pkg):.3f} / {jpt(e_ram):.4f} / {jpt(e_sys):.3f}")
        print(f"  tokens/s (active)     : {tps:.2f}")
    print(f"  memory                : max RAM used {ram_used:.2f} GB, max swap {swap_max:.0f} MB")
    if n_mm == 0:
        print("  NOTE: no macmon samples - check that `macmon pipe` works.")

    new = not os.path.exists("results.csv")
    with open("results.csv", "a", newline="") as f:
        w = csv.writer(f)
        if new:
            w.writerow(["name", "active_s", "tokens", "tokens_per_s",
                        "idle_pkg_w", "run_pkg_w", "run_pkg_macmon_w",
                        "idle_sys_w", "run_sys_w", "idle_ram_w", "run_ram_w",
                        "net_pkg_J", "net_ram_J", "net_sys_J",
                        "J_per_token_pkg", "J_per_token_ram", "J_per_token_sys",
                        "max_ram_used_gb", "max_swap_mb"])
        w.writerow([args.name, f"{dur:.2f}", tok, f"{tps:.3f}",
                    f"{idle_pkg:.3f}", f"{run_pkg:.3f}", f"{run_mm_pkg:.3f}",
                    f"{idle_sys:.3f}", f"{run_sys:.3f}", f"{idle_ram:.4f}", f"{run_ram:.4f}",
                    f"{e_pkg:.2f}", f"{e_ram:.3f}", f"{e_sys:.2f}",
                    f"{jpt(e_pkg):.4f}", f"{jpt(e_ram):.5f}", f"{jpt(e_sys):.4f}",
                    f"{ram_used:.2f}", f"{swap_max:.0f}"])


if __name__ == "__main__":
    main()
